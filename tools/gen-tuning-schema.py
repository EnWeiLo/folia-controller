#!/usr/bin/env python3
"""Builds shared/web/fc-tuning-schema.js (the settings panel's list of Folia options) from
tools/folia-schema.json, an inventory of Folia's cfg-settable options taken from its source.

Labels come from Folia's zh-CN translations, converted to Taiwan Traditional with OpenCC's
dictionaries: python3 tools/gen-tuning-schema.py <path to OpenCC/data/dictionary>
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if len(sys.argv) > 1:
    os.environ['OPENCC_DICT'] = sys.argv[1]
sys.path.insert(0, HERE)
import s2tw  # noqa: E402

FIXES = [('自定義', '自訂'), ('質量', '品質'), ('默認', '預設'), ('視頻', '影片'), ('屏幕', '螢幕'),
         ('錶情包', '表情貼圖'), ('錶情', '表情'), ('型別', '類型'), ('新增模糊', '加上模糊'), ('新增封面', '加上封面'),
         ('字號', '字級'), ('拖拽', '拖曳'), ('鏡臺', '鏡台'), ('迴環', '回環'), ('當前', '目前'), ('畫素', '像素')]


def tw(text):
    if not isinstance(text, str):
        return text
    out = s2tw.conv(text)
    for a, b in FIXES:
        out = out.replace(a, b)
    return out


# Already set elsewhere in our apps (animation choice, quality, the 副歌詞 setting) or not usable here.
SKIP_GLOBAL = {'visualizerMode', 'staticMode', 'subtitleContentMode', 'showSubtitleTranslation',
               'lyricsFontFallbackFamilies', 'subtitleFontFallbackFamilies'}
SKIP_BACKGROUNDS = {'url'}
# Cadenza has no settings panel in Folia, so no labels or ranges; these are ours.
CADENZA = {
    'fontScale': ('字級', 0.8, 1.6, 0.02),
    'widthRatio': ('文字寬度比例', 0.5, 0.95, 0.01),
    'motionAmount': ('動態幅度', 0, 2, 0.05),
    'glowIntensity': ('光暈強度', 0, 2, 0.05),
}


# No effect on the page our apps show (see notes in folia-schema.json).
SKIP_FIELDS = {'dynamicOnlyInPlayer'}
# Audio-driven options only work with 跟著音樂律動 (fc-audio.js) on.
AUDIO_WORDS = ('音訊', '音樂', '節拍', '頻譜')
AUDIO_HINT = '要先在設定打開「跟著音樂律動」才有效果'


def field(f):
    if f.get('noPanel') or f['key'] in SKIP_FIELDS:
        return None
    out = {'key': f['key'], 'type': f['type'], 'label': tw(f.get('label') or f['key'])}
    for k in ('min', 'max', 'step', 'unit', 'integer', 'nullable', 'presets'):
        if k in f:
            out[k] = f[k]
    if f.get('hint'):
        out['hint'] = tw(f['hint'])
    if f.get('section'):
        out['section'] = tw(f['section'])
    if f.get('showWhen'):
        out['showWhen'] = f['showWhen']
    if f.get('options'):
        opts = [{'value': o['value'], 'label': tw(o.get('label') or str(o['value']))}
                for o in f['options'] if not o.get('requiresUpload')]
        if len(opts) < 2:
            return None
        out['options'] = opts
    if f['type'] == 'string' and f.get('array'):
        return None
    if f['type'] == 'string' and f['key'].endswith('Color'):
        out['type'] = 'color'
    if any(w in out['label'] for w in AUDIO_WORDS) and out['type'] != 'enum':
        out['hint'] = AUDIO_HINT
    return out


def main():
    src = json.load(open(os.path.join(HERE, 'folia-schema.json'), encoding='utf-8'))
    modes = {}
    for mode, m in src['modes'].items():
        fields = []
        if mode == 'cadenza':
            for key, (label, lo, hi, step) in CADENZA.items():
                fields.append({'key': key, 'type': 'number', 'label': label, 'min': lo, 'max': hi, 'step': step})
        for f in m['fields'] if mode != 'cadenza' else []:
            g = field(f)
            if g:
                fields.append(g)
        defaults = dict(m.get('defaults', {}))
        if mode == 'tempera':
            defaults['layerImages'] = []
        if mode == 'cadenza':
            defaults['beamIntensity'] = 0
        modes[mode] = {'label': tw(m['label']), 'defaults': defaults, 'fields': fields}
    glob = [g for g in (field(dict(f, key=f['cfgKey'])) for f in src['global'] if f['cfgKey'] not in SKIP_GLOBAL) if g]
    for g in glob:
        if g['key'] == 'visualizerBackgroundMode':
            g['options'] = [o for o in g['options'] if o['value'] not in SKIP_BACKGROUNDS]
    defaults = {f['cfgKey']: f.get('default') for f in src['global']}
    backgrounds = {}
    for name, b in src['backgrounds'].items():
        if name in SKIP_BACKGROUNDS:
            continue
        backgrounds[name] = {
            'label': tw(b['label']), 'cfgKey': b.get('cfgKey'), 'defaults': b.get('defaults', {}),
            'fields': [g for g in (field(f) for f in b['fields']) if g],
        }
    schema = {'folia': '43e7846', 'modes': modes, 'global': glob, 'globalDefaults': defaults, 'backgrounds': backgrounds}
    target = os.path.join(ROOT, 'shared', 'web', 'fc-tuning-schema.js')
    with open(target, 'w', encoding='utf-8') as out:
        out.write('// Generated by tools/gen-tuning-schema.py from tools/folia-schema.json. Do not edit by hand.\n')
        out.write('window.FC_FOLIA_SCHEMA = ')
        json.dump(schema, out, ensure_ascii=False, separators=(',', ':'))
        out.write(';\n')
    print(f'{target}: {sum(len(m["fields"]) for m in modes.values())} mode fields, {len(glob)} global, '
          f'{sum(len(b["fields"]) for b in backgrounds.values())} background fields')


main()
